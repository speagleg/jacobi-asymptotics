"""JZC_W2 §3: the registered second-order pole predictions (w2_predictions.json, w2_predict.py) against the Jacobi coefficients of
sigma^{delta,kappa} (w2_data.py: double-double atoms, binary128 RKPW, y in mpmath). NUMERICAL (Rule N): fits are not error bounds.
Protocol (Rule X): the script asserts that the predictions file was written before this run started and that every data file it
uses is newer than the predictions. The fit method below was fixed in this file before any data of these measures existed
(a first data file generated by a timing test before registration was deleted unread, JZC_W2 Rule A item 1).
Fit of the coefficient of n^{-T}: r_n = y_n - sum_{e <= emax, e != T} P_e n^{-e} (P = registered prediction, all orders),
least squares on n in [lo, 1200] with columns n^{-T} and the first J-1 half-integer exponents > emax (unknown layers),
J in {2, 3, 4, 5}, lo in {150, 300, 600}; median and half-range; tol = max(3 half-ranges, 1e-9 (1 + |P_T|)).
Assertions: |fit - P_T| <= tol at T1 = 2p and T2 = 1 + 2p; the alternatives A0 (no second order in the poles), A1 (Toda-only
bracket), A2 (naive exponentiation) must miss by > 10 tol at T1; A3 (naive square) by > 3 tol at T1 (all decided before data);
at T2 the misses are reported. kappa-structure at T1: fit(k) - fit(-k) = 0 within tol, and the kappa^2 coefficient
C = (fit(k) - fit(k/2))/(3k^2/4) equals the registered one within the propagated tol. Tail control: one case per p re-run with
Kfac = 200 (the continuum tail moved twice as far): the T1, T2 fits must agree within tol.
Usage: python w2_fit.py [P15|P25]"""
import os, sys, json, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
T_START = time.time()
import numpy as np, mpmath as mp
import w2_common as W, w2_data as D
FAM = sys.argv[1] if len(sys.argv) > 1 else 'P15'
PF = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'w2_predictions.json')
W.provenance(__file__, D.__file__, W.__file__, PF)
REG = json.load(open(PF)); print(f"predictions registered {REG['written']}; this run started {time.strftime('%Y-%m-%d %H:%M:%S %Z')}", flush=True)
NCHK = 0; FAILS = []
def chk(label, ok):
    global NCHK
    NCHK += 1
    if not ok: FAILS.append(label)
    print(f"  [{NCHK}] {label}: {'PASS' if ok else 'FAIL'}", flush=True)
chk("Rule X: predictions written before this run", REG['unix'] < T_START)
NMAX = 1200


def fit(n, y, pred, T, emax, los=(150, 300, 600), Js=(2, 3, 4, 5)):
    r = [yy - sum(v*mp.mpf(int(nn))**(-mp.mpf(e)) for e, v in pred.items() if abs(e - T) > 1e-9) for nn, yy in zip(n, y)]
    r = np.array([float(x) for x in r]); nf = n.astype(float)
    nuis = [emax + 0.5*i for i in range(1, 8)]
    est = []
    for J in Js:
        E = [T] + nuis[:J - 1]
        for lo in los:
            m = nf >= lo; A = np.vstack([nf[m]**(-e) for e in E]).T
            sc = np.abs(A).max(axis=0); est.append((np.linalg.lstsq(A/sc, r[m], rcond=None)[0]/sc)[0])
    est = np.array(est); return float(np.median(est)), float((est.max() - est.min())/2)


res = {}
for key, C in REG['cases'].items():
    if not key.startswith(FAM): continue
    emax = C['emax']; pred = {float(e): mp.mpf(v) for e, v in C['pred'].items()}
    n, y = D.data(C['p'], C['d'], C['kap'], C['s'], nmax=NMAX, Kfac=100)
    chk(f"{key} Rule X: data file newer than predictions ({os.path.basename(D.LAST)}, tail model {D.TAIL})", os.path.getmtime(D.LAST) > REG['unix'])
    print(f"=== {key}: p={C['p']} d={C['d']} kappa={C['kap']} s={C['s']} (alpha={C['alpha']}, beta'={C['betap']}) ===", flush=True)
    # informational: residual after the full prediction
    nn = np.array([150, 300, 600, 1200])
    rr = [float(y[k - 1] - sum(v*mp.mpf(int(k))**(-mp.mpf(e)) for e, v in pred.items())) for k in nn]
    print("   residual y - P (all e <= emax) at n = 150, 300, 600, 1200: " + ", ".join(f"{x:+.3e}" for x in rr)
          + f"   (x n^{emax + 0.5}: " + ", ".join(f"{x*k**(emax + 0.5):+.3f}" for x, k in zip(rr, nn)) + ")", flush=True)
    res[key] = {}
    for T in C['targets']:
        f, hr = fit(n, y, pred, T, emax); P_T = float(pred[T]); tol = max(3*hr, 1e-9*(1 + abs(P_T)))
        sec = sum(float(mp.mpf(v)) for e, v, l, o in C['terms'] if abs(e - T) < 1e-9 and o >= 2)
        res[key][T] = (f, hr, tol)
        print(f"   n^-{T}: fit {f:+.10f} (half-range {hr:.1e})  registered {P_T:+.10f}  diff {f - P_T:+.2e} = {abs(f - P_T)/tol:.2f} tol"
              f"   [second+third-order part {sec:+.6f} = {abs(sec)/tol:.0f} tol]", flush=True)
        chk(f"{key} n^-{T}: registered prediction (all orders in the times)", abs(f - P_T) <= tol)
        for nm, A in C['alts'].items():
            a = float(mp.mpf(A[str(T)])) if str(T) in A else 0.0
            miss = abs(f - a)/tol
            line = f"      alternative {nm:13s}: {a:+.10f}  misses by {miss:.1f} tol"
            if abs(T - C['targets'][0]) < 1e-9:
                thr = 3 if nm.startswith('A3') else 10
                chk(f"{key} n^-{T}: alternative {nm} must miss by > {thr} tol", miss > thr); line += f" (asserted > {thr})"
            print(line, flush=True)

# kappa structure at T1
keys = sorted(res); a_, b_, c_ = keys                     # +k, -k, +k/2
T1 = REG['cases'][a_]['targets'][0]
k = float(mp.mpf(eval(REG['cases'][a_]['kap'].replace('/', '/'))))
fa, fb, fc = (res[x][T1] for x in (a_, b_, c_))
chk(f"kappa-structure n^-{T1}: fit(+k) = fit(-k) (even in kappa)", abs(fa[0] - fb[0]) <= fa[2] + fb[2])
Chat = (fa[0] - fc[0])/(0.75*k*k); Ctol = (fa[2] + fc[2])/(0.75*k*k)
Pa, Pc = (float(mp.mpf(REG['cases'][x]['pred'][str(T1)])) for x in (a_, c_)); Cpred = (Pa - Pc)/(0.75*k*k)
A0a, A0c = (float(mp.mpf(REG['cases'][x]['alts']['A0 none'][str(T1)])) for x in (a_, c_)); CA0 = (A0a - A0c)/(0.75*k*k)
print(f"   kappa^2 coefficient at n^-{T1}: fitted {Chat:+.8f} +- {Ctol:.1e}, registered {Cpred:+.8f} "
      f"(of which first order (q2) {CA0:+.8f}, second order (q1^2) {Cpred - CA0:+.8f})", flush=True)
chk(f"kappa^2 coefficient at n^-{T1} = registered", abs(Chat - Cpred) <= Ctol)
chk(f"kappa^2 coefficient at n^-{T1}: first-order-only value must miss by > 10 tol", abs(Chat - CA0) > 10*Ctol)

# tail control
key = a_; C = REG['cases'][key]; pred = {float(e): mp.mpf(v) for e, v in C['pred'].items()}
n, y2 = D.data(C['p'], C['d'], C['kap'], C['s'], nmax=NMAX, Kfac=200)
for T in C['targets']:
    f2, hr2 = fit(n, y2, pred, T, C['emax']); f1, hr1, tol = res[key][T]
    print(f"   tail control {key} n^-{T}: Kfac 200 fit {f2:+.10f} vs Kfac 100 {f1:+.10f} (diff {f2 - f1:+.1e}, {abs(f2 - f1)/tol:.2f} tol)", flush=True)
    chk(f"tail control {key} n^-{T}: Kfac 100 and 200 agree within tol", abs(f2 - f1) <= tol)
print(f"ALL {NCHK} CHECKS PASSED" if not FAILS else f"{len(FAILS)} OF {NCHK} CHECKS FAILED: " + "; ".join(FAILS))
